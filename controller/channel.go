func UpdateChannel(c *gin.Context) {
	// 先读并缓存原始请求体（用于判断是否携带 support_responses），
	// GetRequestBody 不恢复 Body，这里手动恢复供 ShouldBindJSON 使用
	requestBody, _ := common.GetRequestBody(c)
	c.Request.Body = io.NopCloser(bytes.NewBuffer(requestBody))
	channel := model.Channel{}
	err := c.ShouldBindJSON(&channel)
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	if c.Query("schedule_only") != "" {
		// 仅更新定时启停配置，不影响其他字段
		err = channel.UpdateSchedule()
		if err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
		c.JSON(http.StatusOK, gin.H{
			"success": true,
			"message": "",
			"data":    channel,
		})
		return
	}
	// channel.Update() 内部会从 DB 重读整行覆盖结构体，
	// 因此在调用前先保存请求期望的 support_responses 值
	wantSupportResponses := channel.SupportResponses
	wantModelContext := channel.ModelContext
	err = channel.Update()
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	// 仅当请求体明确携带 support_responses 时才单独更新该字段，
	// 避免启用/禁用等部分更新（{id,status}）把布尔零值误写回
	if bytes.Contains(requestBody, []byte("\"support_responses\"")) {
		channel.SupportResponses = wantSupportResponses
		if err = channel.UpdateSupportResponses(); err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
	}
	// model_context 允许写空值（清空配置），同样单独更新
	if bytes.Contains(requestBody, []byte("\"model_context\"")) {
		if err = model.DB.Model(channel).UpdateColumn("model_context", wantModelContext).Error; err != nil {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": err.Error(),
			})
			return
		}
		channel.ModelContext = wantModelContext
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    channel,
	})
	return
}
